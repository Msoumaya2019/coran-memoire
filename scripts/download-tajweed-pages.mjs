import {createHash} from 'node:crypto';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import {join} from 'node:path';

// Run only for the complete licensed Hafs colour-page edition. Metro needs
// static require() calls, which this script regenerates after checking all pages.
const root=new URL('../',import.meta.url).pathname.replace(/^\/(?:[A-Za-z]:)/,match=>match.slice(1));
const output=join(root,'assets','tajweed');
const source='https://raw.githubusercontent.com/QuranHub/quran-pages-images/main/easyquran.com/hafs-tajweed';
await mkdir(output,{recursive:true});
const hashes=Array(605).fill(null);
let cursor=1;
async function worker(){
  while(cursor<=604){
    const page=cursor++;
    const filename=join(output,`page${String(page).padStart(3,'0')}.jpg`);
    let bytes;
    try{bytes=await readFile(filename);}catch{}
    if(!bytes){
      let lastError;
      for(let attempt=0;attempt<4;attempt++){
        try{
          const response=await fetch(`${source}/${page}.jpg`);
          if(!response.ok)throw new Error(`HTTP ${response.status}`);
          bytes=Buffer.from(await response.arrayBuffer());
          break;
        }catch(error){lastError=error;await new Promise(resolve=>setTimeout(resolve,500*(attempt+1)));}
      }
      if(!bytes)throw new Error(`Page ${page}: ${lastError?.message}`);
      await writeFile(filename,bytes);
    }
    if(bytes.length<10000||bytes[0]!==0xff||bytes[1]!==0xd8||bytes.at(-2)!==0xff||bytes.at(-1)!==0xd9)throw new Error(`JPEG invalide : page ${page}`);
    hashes[page]=createHash('sha256').update(bytes).digest('hex');
    if(page%50===0)process.stdout.write(`${page}/604\n`);
  }
}
await Promise.all(Array.from({length:8},worker));
if(hashes.slice(1).some(hash=>!hash))throw new Error('Il manque des pages.');
const imports=Array.from({length:604},(_,index)=>`  require('../../assets/tajweed/page${String(index+1).padStart(3,'0')}.jpg'),`).join('\n');
await writeFile(join(root,'src','data','tajweedImages.ts'),`// Generated by scripts/download-tajweed-pages.mjs. Index 0 is intentionally empty.\nexport const tajweedImages=[null,\n${imports}\n] as const;\n`);
await writeFile(join(root,'src','data','tajweedImageHashes.json'),JSON.stringify({edition:'easyquran.com/hafs-tajweed',source,sha256:hashes.slice(1)},null,2)+'\n');
console.log('604 pages JPEG contrôlées.');
