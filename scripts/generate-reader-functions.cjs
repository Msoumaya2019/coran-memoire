const fs=require('fs'),path=require('path'),ts=require('typescript');
const root=path.resolve(__dirname,'..');
const functions={annotationRegions:'src/core/readerAnnotations.ts',marginAnnotations:'src/core/marginAnnotations.ts',pressurePaths:'src/core/tabletInk.ts',inkShapePath:'src/core/tabletInk.ts',inkHit:'src/core/tabletInk.ts'};
function generated(){
 const source={};
 for(const [name,file]of Object.entries(functions)){
  const tree=ts.createSourceFile(file,fs.readFileSync(path.join(root,file),'utf8'),ts.ScriptTarget.Latest,true);
  const node=tree.statements.find(n=>ts.isFunctionDeclaration(n)&&n.name?.text===name);
  if(!node)throw Error('Missing standalone reader helper: '+name);
  source[name]=ts.transpileModule(node.getText(tree).replace(/^export\s+/,''),{compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.ESNext,removeComments:true,alwaysStrict:false}}).outputText.trim();
 }
 return '// Generated by scripts/generate-reader-functions.cjs. Do not edit manually.\n// Literal JavaScript is required: Hermes does not preserve Function.toString source.\nexport const readerFunctionSources = '+JSON.stringify(source,null,2)+' as const;\n';
}
const target=path.join(root,'src/coranTest/readerFunctions.generated.ts'),content=generated();
if(process.argv.includes('--check')){
 if(!fs.existsSync(target)||fs.readFileSync(target,'utf8').replaceAll('\r\n','\n')!==content){console.error('Reader helper scripts are stale. Run: node scripts/generate-reader-functions.cjs');process.exitCode=1;}
}else fs.writeFileSync(target,content);
